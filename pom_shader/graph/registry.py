from __future__ import annotations

import bpy

from .groups import frame, main, march_linear, normal, refine, setup, shadow

GROUP_VERSION = 2

MODULES = (frame, setup, march_linear, refine, normal, shadow, main)
NAMES = tuple(m.NAME for m in MODULES)
MAIN = main.NAME


def find(name: str) -> bpy.types.NodeTree | None:
    for tree in bpy.data.node_groups:
        if tree.bl_idname == "ShaderNodeTree" and tree.get("rpom_group") == name:
            return tree
    return None


def version_of(tree: bpy.types.NodeTree) -> int:
    return int(tree.get("rpom_version", 0))


def outdated() -> list[bpy.types.NodeTree]:
    return [t for t in bpy.data.node_groups if t.get("rpom_group") and version_of(t) < GROUP_VERSION]


def _clear(tree: bpy.types.NodeTree) -> None:
    tree.nodes.clear()
    tree.interface.clear()


def _tree_for(name: str, force: bool) -> tuple[bpy.types.NodeTree, bool]:
    tree = find(name)
    if tree is None:
        return bpy.data.node_groups.new(name, "ShaderNodeTree"), True
    if force or version_of(tree) < GROUP_VERSION:
        _clear(tree)
        return tree, True
    return tree, False


def _mark(tree: bpy.types.NodeTree, name: str) -> None:
    tree["rpom_group"] = name
    tree["rpom_version"] = GROUP_VERSION
    tree.description = "POM Shader: generated by the add-on, do not edit by hand"


def ensure_hex_groups(force: bool = False) -> dict[str, bpy.types.NodeTree]:
    from .groups import hextile

    trees = {}
    for name, build in hextile.BUILDERS.items():
        tree, todo = _tree_for(name, force)
        if todo:
            build(tree)
            _mark(tree, name)
        trees[name] = tree
    return trees


def ensure_groups(force: bool = False) -> dict[str, bpy.types.NodeTree]:
    trees: dict[str, bpy.types.NodeTree] = {}
    for mod in MODULES:
        tree, todo = _tree_for(mod.NAME, force)
        if todo:
            if mod is main:
                mod.build(tree, trees)
            else:
                mod.build(tree)
            _mark(tree, mod.NAME)
        trees[mod.NAME] = tree
    return trees
